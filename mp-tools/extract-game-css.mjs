/* Lift the game screen's styling out of the H5 stylesheets.
 *
 * The full converted game.css carries every screen plus ~480KB of inlined
 * images; the mini-program only renders the game screen so far, so this pulls
 * just those rules, in cascade order, and rewrites what WXSS cannot express:
 * element selectors (there are no <b>/<span>/<svg> tags) and the #game prefix
 * (the page root is the game).
 */
import fs from 'fs';
import path from 'path';

const H5 = 'C:/mydev/majiang/majiangxiaoxiaole';
const OUT = 'C:/mydev/majiang/majiang-mp/src/styles/game-screen.css';

const FILES = ['styles.css', ...Array.from({ length: 24 }, (_, i) => `styles-v${37 + i}.css`)];
// Rules worth carrying over: the HUD, tray, tool dock and the board frame.
// The tool pills' colour comes from .icon-* rules that sit outside the .g-* family.
const KEEP = /#game\.game|\.(g-[\w-]+|icon-[\w-]+|board-wrap|board|coach|toast)\b/;
// Tag selectors have no equivalent in WXML, so the template uses these classes.
const TAGS = { b: '.t-b', i: '.t-i', span: '.t-span', svg: '.t-icon', small: '.t-small', p: '.t-p', nav: '.t-nav', header: '.t-header', main: '.t-main', div: '.t-div', button: '.t-btn' };

function splitTop(s, sep = ',') {
  const out = []; let buf = '', depth = 0;
  for (const ch of s) {
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth--;
    if (ch === sep && depth === 0) { out.push(buf); buf = ''; } else buf += ch;
  }
  out.push(buf);
  return out;
}

function convert(sel) {
  let s = sel.replace(/\s+/g, ' ').trim();
  if (/:focus-visible|:has\(|input|:checked/.test(s)) return null;
  s = s.replace(/#game\.game/g, '.game').replace(/#gRulesBtn/g, '.g-rules').replace(/#gMoreBtn/g, '.g-more').replace(/#gQuitBtn/g, '.g-quit').replace(/#game\s*/g, '').replace(/\.screen\.game\s*/g, '').replace(/#boardWrap/g, '.board-wrap').replace(/#board\b/g, '.board').replace(/#slotTray/g, '.g-tray').replace(/#comboFill/g, '.g-combo-fill').replace(/#comboText/g, '.g-combo-text').replace(/#toast/g, '.toast').replace(/#coach/g, '.coach');
  s = s.replace(/(^|[\s,>+~])(b|i|span|svg|small|p|nav|header|main|div|button)(?=[\s,.:#[>+~]|$)/g, (m, pre, tag) => pre + TAGS[tag]);
  return s.trim() || null;
}

let css = '';
let kept = 0, dropped = 0;
for (const f of FILES) {
  const src = fs.readFileSync(path.join(H5, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  // @media blocks are phone-size tweaks the mini-program does not need.
  const flat = src.replace(/@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, '');
  for (const m of flat.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const prelude = m[1].trim();
    if (prelude.startsWith('@')) continue;
    const sels = splitTop(prelude).map(x => x.trim()).filter(Boolean);
    if (!sels.some(x => KEEP.test(x))) continue;
    const out = sels.filter(x => KEEP.test(x)).map(convert).filter(Boolean);
    if (!out.length) { dropped++; continue; }
    css += out.join(',') + '{' + m[2].trim() + '}\n';
    kept++;
  }
}

// WXSS background-image cannot take a local path, so the decorative art that the
// board frame pulls in has to travel as a data URI.
const B64 = 'C:/mydev/majiang/mp-tools/static-out/b64';
for (const [file, key] of [['lotus-lines.svg', 'lotus-lines.png'], ['bamboo-shadow.svg', 'bamboo-shadow.png'],
                           ['game-table-v1.png', 'game-table.jpg'], ['home-tree-v1.png', 'home-tree.jpg']]) {
  const data = path.join(B64, key + '.txt');
  if (!fs.existsSync(data)) continue;
  const uri = fs.readFileSync(data, 'utf8');
  css = css.split(`url("assets/${file}")`).join(`url("${uri}")`)
           .split(`url('assets/${file}')`).join(`url("${uri}")`)
           .split(`url(assets/${file})`).join(`url("${uri}")`);
}

// Carry over only the keyframes something still animates.
const used = new Set();
for (const m of css.matchAll(/animation(?:-name)?\s*:[^;}]+/g)) {
  for (const tok of m[0].match(/[A-Za-z_][\w-]*/g) || []) used.add(tok);
}
for (const f of FILES) {
  const src = fs.readFileSync(path.join(H5, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of src.matchAll(/@keyframes\s+([\w-]+)\s*\{/g)) {
    if (!used.has(m[1])) continue;
    let depth = 1, i = m.index + m[0].length;
    while (i < src.length && depth > 0) { if (src[i] === '{') depth++; else if (src[i] === '}') depth--; i++; }
    css += src.slice(m.index, i) + '\n';
  }
}

const leftover = (css.match(/url\((?!["']?data:)/g) || []).length;
if (leftover) console.log('WARNING: ' + leftover + ' url() still point at local files; WXSS will not load them');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `/* Generated by mp-tools/extract-game-css.mjs - do not edit by hand. */\n${css}`);
console.log(`kept ${kept} rules (${(css.length / 1024).toFixed(1)}KB), dropped ${dropped} unsupported -> ${OUT}`);
