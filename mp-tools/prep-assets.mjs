// 4. CSS 引用的大图转 base64（wxss 的 background-image 只支持 data URI / 网络图）
async function cssAsset(srcFile, outName) {
  const buf = await sharp(path.join(SRC, srcFile)).toBuffer();
  const ext = outName.endsWith('.jpg') ? 'jpeg' : 'png';
  const b64 = `data:image/${ext};base64,${buf.toString('base64')}`;
  fs.writeFileSync(path.join(B64, outName + '.txt'), b64);
  report.push(`${srcFile} -> ${outName} ${(buf.length / 1024).toFixed(0)}KB`);
}
